const languageButtons = [...document.querySelectorAll("[data-language]")];
const translatableElements = [...document.querySelectorAll("[data-i18n]")];
const translatableAriaLabels = [...document.querySelectorAll("[data-i18n-aria-label]")];
const translatableAltTexts = [...document.querySelectorAll("[data-i18n-alt]")];
const menuToggle = document.querySelector(".menu-toggle");
const navigation = document.querySelector(".site-nav");
const siteHeader = document.querySelector(".site-header");
const descriptionMeta = document.querySelector('meta[name="description"]');
const brandLink = document.querySelector(".brand");
const languageSwitcher = document.querySelector(".language-switcher");
const terminalCard = document.querySelector(".terminal-card");
const mobileNavigationQuery = window.matchMedia("(max-width: 900px)");
const reducedMotionQuery = window.matchMedia("(prefers-reduced-motion: reduce)");

function addMediaQueryListener(query, listener) {
  if (typeof query.addEventListener === "function") {
    query.addEventListener("change", listener);
  } else if (typeof query.addListener === "function") {
    query.addListener(listener);
  }
}

function getStoredLanguage() {
  try {
    return window.localStorage.getItem("portfolio-language");
  } catch {
    return null;
  }
}

function storeLanguage(language) {
  try {
    window.localStorage.setItem("portfolio-language", language);
  } catch {
    // Language persistence is optional.
  }
}

function applyLanguage(language) {
  const activeLanguage = Object.prototype.hasOwnProperty.call(translations, language) ? language : "en";
  const dictionary = translations[activeLanguage];

  document.documentElement.lang = activeLanguage;
  document.title = dictionary.pageTitle;
  if (descriptionMeta) descriptionMeta.content = dictionary.pageDescription;

  translatableElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  translatableAriaLabels.forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (dictionary[key]) element.setAttribute("aria-label", dictionary[key]);
  });

  translatableAltTexts.forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (dictionary[key]) element.setAttribute("alt", dictionary[key]);
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === activeLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  if (menuToggle) {
    const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute("aria-label", dictionary[isOpen ? "menuClose" : "menuOpen"]);
  }

  brandLink?.setAttribute("aria-label", dictionary.brandHome);
  navigation?.setAttribute("aria-label", dictionary.navAria);
  languageSwitcher?.setAttribute("aria-label", dictionary.languageAria);
  terminalCard?.setAttribute("aria-label", dictionary.profileAria);

  storeLanguage(activeLanguage);
}

function setMenuState(isOpen) {
  if (!menuToggle || !navigation) return;
  const shouldOpen = mobileNavigationQuery.matches && isOpen;
  navigation.classList.toggle("is-open", shouldOpen);
  navigation.toggleAttribute("inert", mobileNavigationQuery.matches && !shouldOpen);
  menuToggle.setAttribute("aria-expanded", String(shouldOpen));
  const language = document.documentElement.lang in translations ? document.documentElement.lang : "en";
  menuToggle.setAttribute("aria-label", translations[language][shouldOpen ? "menuClose" : "menuOpen"]);
}

function closeMenu() {
  setMenuState(false);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.language));
});

if (menuToggle && navigation) {
  menuToggle.addEventListener("click", () => {
    setMenuState(!navigation.classList.contains("is-open"));
  });

  navigation.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));
  document.addEventListener("click", (event) => {
    if (!navigation.classList.contains("is-open")) return;
    if (navigation.contains(event.target) || menuToggle.contains(event.target)) return;
    closeMenu();
  });
  document.addEventListener("keydown", (event) => {
    if (event.key !== "Escape" || !navigation.classList.contains("is-open")) return;
    closeMenu();
    menuToggle.focus();
  });
  addMediaQueryListener(mobileNavigationQuery, closeMenu);
  setMenuState(false);
  document.documentElement.classList.add("nav-ready");
}

const storedLanguage = getStoredLanguage();
const preferredLanguage = Object.prototype.hasOwnProperty.call(translations, storedLanguage)
  ? storedLanguage
  : (navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en");
applyLanguage(preferredLanguage);
document.documentElement.classList.add("i18n-ready");

const currentYear = document.getElementById("current-year");
if (currentYear) currentYear.textContent = new Date().getFullYear();

function updateHeader() {
  siteHeader?.classList.toggle("is-scrolled", window.scrollY > 16);
}

updateHeader();
window.addEventListener("scroll", updateHeader, { passive: true });

const revealElements = [...document.querySelectorAll(".reveal")];
if ("IntersectionObserver" in window && !reducedMotionQuery.matches) {
  try {
    const revealObserver = new IntersectionObserver(
      (entries, observer) => {
        entries.forEach((entry) => {
          if (!entry.isIntersecting) return;
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        });
      },
      { threshold: 0.13, rootMargin: "0px 0px -40px" }
    );

    revealElements.forEach((element) => revealObserver.observe(element));
    document.documentElement.classList.add("reveal-ready");
  } catch {
    revealElements.forEach((element) => element.classList.add("is-visible"));
  }
} else {
  revealElements.forEach((element) => element.classList.add("is-visible"));
}
